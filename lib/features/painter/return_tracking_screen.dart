class ReturnTrackingScreen extends ConsumerWidget {
  final String returnId;
  const ReturnTrackingScreen({super.key, required this.returnId});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final ds = ref.watch(dataServiceProvider);
    final returnRequest = ds.getReturnRequestById(returnId);

    if (returnRequest == null) {
      return Scaffold(
        appBar: AppBar(title: const Text('Track Return')),
        body: const Center(child: Text('Return request not found.')),
      );
    }

    final order = ds.getOrderById(returnRequest.orderId);
    final isActive = !returnRequest.status.isTerminal;

    return Scaffold(
      backgroundColor: AppColors.scaffoldBg,
      appBar: AppBar(
        backgroundColor: Colors.white,
        foregroundColor: AppColors.textPrimary,
        elevation: 0,
        centerTitle: true,
        title: Text(
          returnRequest.displayId,
          style: GoogleFonts.poppins(fontWeight: FontWeight.w600),
        ),
        leading: IconButton(
          icon: const Icon(Icons.arrow_back_ios_new_rounded),
          onPressed: () {
            if (context.canPop()) {
              context.pop();
            } else {
              context.go('/painter/my-returns');
            }
          },
        ),
      ),
      body: SingleChildScrollView(
        padding: EdgeInsets.symmetric(
          horizontal: Responsive.horizontalPadding(context),
          vertical: 20,
        ),
        child: Center(
          child: ConstrainedBox(
            constraints: BoxConstraints(maxWidth: Responsive.contentMaxWidth(context)),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
            // Header card
            _HeaderCard(returnRequest: returnRequest, order: order),
            const SizedBox(height: 20),

            // Return Bill / Credit Note (if generated by admin)
            if (returnRequest.billUrl != null && returnRequest.billUrl!.isNotEmpty) ...[
              _ReturnBillCard(returnRequest: returnRequest),
              const SizedBox(height: 20),
            ],

            // Items
            if (returnRequest.items.isNotEmpty) ...[
              _ItemsCard(returnRequest: returnRequest),
              const SizedBox(height: 20),
            ],

            // Timeline
            _buildTimeline(returnRequest),
            const SizedBox(height: 20),

            // Admin note / rejection reason
            if (returnRequest.cleanAdminNote != null &&
                returnRequest.cleanAdminNote!.isNotEmpty) ...[
              Container(
                width: double.infinity,
                padding: const EdgeInsets.all(16),
                decoration: BoxDecoration(
                  color: returnRequest.status == ReturnStatus.rejected
                      ? AppColors.error.withValues(alpha: 0.06)
                      : AppColors.info.withValues(alpha: 0.06),
                  borderRadius: BorderRadius.circular(14),
                  border: Border.all(
                    color: returnRequest.status == ReturnStatus.rejected
                        ? AppColors.error.withValues(alpha: 0.25)
                        : AppColors.info.withValues(alpha: 0.25),
                  ),
                ),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      returnRequest.status == ReturnStatus.rejected
                          ? 'Rejection Reason'
                          : 'Admin Note',
                      style: GoogleFonts.poppins(
                        fontSize: 12,
                        fontWeight: FontWeight.w700,
                        color: returnRequest.status == ReturnStatus.rejected
                            ? AppColors.error
                            : AppColors.info,
                      ),
                    ),
                    const SizedBox(height: 6),
                    Text(
                      returnRequest.cleanAdminNote!,
                      style: GoogleFonts.poppins(
                        fontSize: 13,
                        color: AppColors.textPrimary,
                      ),
                    ),
                  ],
                ),
              ),
              const SizedBox(height: 20),
            ],

            // Cancel button (if eligible)
            if (isActive && returnRequest.status.canBeCancelledByUser)
              _CancelButton(returnId: returnId),

            const SizedBox(height: 40),
          ],
        ),
      ),
    ),
  ),
);
  }

  Widget _buildTimeline(ReturnRequestModel r) {
    final steps = _buildTimelineSteps(r);

    return Container(
      padding: const EdgeInsets.all(16),
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(16),
        border: Border.all(color: Colors.grey.shade200),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(
            'Return Timeline',
            style: GoogleFonts.poppins(
              fontSize: 13,
              fontWeight: FontWeight.w700,
              color: AppColors.textSecondary,
            ),
          ),
          const SizedBox(height: 16),
          ...steps.asMap().entries.map((entry) {
            final i = entry.key;
            final step = entry.value;
            final isLast = i == steps.length - 1;
            return _TimelineRow(
              step: step,
              showLine: !isLast,
            );
          }),
        ],
      ),
    );
  }

  List<_TimelineStep> _buildTimelineSteps(ReturnRequestModel r) {
    // For rejected returns: show up to rejected step
    if (r.status == ReturnStatus.rejected) {
      return [
        _TimelineStep(
          label: 'Return Requested',
          timestamp: r.requestedAt,
          isDone: true,
          icon: Icons.assignment_return_rounded,
        ),
        _TimelineStep(
          label: 'Return Rejected',
          timestamp: r.rejectedAt ?? r.updatedAt,
          isDone: true,
          icon: Icons.cancel_rounded,
          color: AppColors.error,
        ),
      ];
    }

    // For cancelled: show up to cancelled step
    if (r.status == ReturnStatus.cancelled) {
      return [
        _TimelineStep(
          label: 'Return Requested',
          timestamp: r.requestedAt,
          isDone: true,
          icon: Icons.assignment_return_rounded,
        ),
        _TimelineStep(
          label: 'Cancelled',
          timestamp: r.updatedAt,
          isDone: true,
          icon: Icons.do_not_disturb_on_rounded,
          color: AppColors.textSecondary,
        ),
      ];
    }

    // Normal forward flow
    final ordered = [
      ReturnStatus.requested,
      ReturnStatus.approved,
      ReturnStatus.pickupScheduled,
      ReturnStatus.pickedUp,
      ReturnStatus.received,
      ReturnStatus.refundProcessing,
      ReturnStatus.refunded,
    ];

    final currentIdx = ordered.indexOf(r.status);

    return [
      _TimelineStep(
        label: 'Return Requested',
        timestamp: r.requestedAt,
        isDone: true,
        icon: Icons.assignment_return_rounded,
      ),
      _TimelineStep(
        label: 'Return Approved',
        timestamp: r.approvedAt,
        isDone: currentIdx >= 1,
        icon: Icons.check_circle_rounded,
      ),
      _TimelineStep(
        label: 'Pickup Scheduled',
        timestamp: r.pickupScheduledAt,
        isDone: currentIdx >= 2,
        icon: Icons.local_shipping_rounded,
      ),
      _TimelineStep(
        label: 'Product Picked Up',
        timestamp: r.pickedUpAt,
        isDone: currentIdx >= 3,
        icon: Icons.inventory_2_rounded,
      ),
      _TimelineStep(
        label: 'Product Received',
        timestamp: r.receivedAt,
        isDone: currentIdx >= 4,
        icon: Icons.warehouse_rounded,
      ),
      _TimelineStep(
        label: 'Refund Processing',
        timestamp: r.refundProcessingAt,
        isDone: currentIdx >= 5,
        icon: Icons.account_balance_wallet_rounded,
        color: currentIdx >= 5 ? const Color(0xFF8B5CF6) : null,
      ),
      _TimelineStep(
        label: 'Refund Completed',
        timestamp: r.refundedAt,
        isDone: currentIdx >= 6,
        icon: Icons.celebration_rounded,
        color: currentIdx >= 6 ? AppColors.success : null,
      ),
    ];
  }
}

// ─── Header card ──────────────────────────────────────────────────────────────

class _HeaderCard extends StatelessWidget {
  final ReturnRequestModel returnRequest;
  final dynamic order;

  const _HeaderCard({required this.returnRequest, required this.order});

  @override
  Widget build(BuildContext context) {
    final statusColor = _statusColor(returnRequest.status);
    return Container(
      width: double.infinity,
      padding: const EdgeInsets.all(16),
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(16),
        border: Border.all(color: Colors.grey.shade200),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              Text(
                returnRequest.displayId,
                style: GoogleFonts.poppins(
                  fontSize: 15,
                  fontWeight: FontWeight.w700,
                  color: AppColors.textPrimary,
                ),
              ),
              Container(
                padding:
                    const EdgeInsets.symmetric(horizontal: 12, vertical: 5),
                decoration: BoxDecoration(
                  color: statusColor.withValues(alpha: 0.12),
                  borderRadius: BorderRadius.circular(20),
                  border: Border.all(color: statusColor.withValues(alpha: 0.3)),
                ),
                child: Text(
                  returnRequest.status.label,
                  style: GoogleFonts.poppins(
                    fontSize: 11,
                    fontWeight: FontWeight.w700,
                    color: statusColor,
                  ),
                ),
              ),
            ],
          ),
          const SizedBox(height: 12),
          if (order != null) ...[
            _infoRow('Order', '#${order.id.substring(0, 8).toUpperCase()}'),
            _infoRow('Brand', order.brand ?? '-'),
          ],
          _infoRow('Reason', returnRequest.reason),
          _infoRow(
            'Requested',
            DateFormat('dd MMM yyyy').format(returnRequest.requestedAt),
          ),
          if (returnRequest.refundAmount > 0)
            _infoRow(
              'Refund Amount',
              '₹${returnRequest.refundAmount.toStringAsFixed(0)}',
            ),
        ],
      ),
    );
  }

  Widget _infoRow(String label, String value) {
    return Padding(
      padding: const EdgeInsets.only(bottom: 6),
      child: Row(
        children: [
          SizedBox(
            width: 100,
            child: Text(
              label,
              style: GoogleFonts.poppins(
                fontSize: 12,
                color: AppColors.textSecondary,
              ),
            ),
          ),
          Expanded(
            child: Text(
              value,
              style: GoogleFonts.poppins(
                fontSize: 12,
                fontWeight: FontWeight.w600,
              ),
            ),
          ),
        ],
      ),
    );
  }
}

Color _statusColor(ReturnStatus status) {
  switch (status) {
    case ReturnStatus.requested:
      return AppColors.warning;
    case ReturnStatus.approved:
      return AppColors.info;
    case ReturnStatus.pickupScheduled:
    case ReturnStatus.pickedUp:
    case ReturnStatus.received:
      return AppColors.info;
    case ReturnStatus.refundProcessing:
      return const Color(0xFF8B5CF6);
    case ReturnStatus.refunded:
      return AppColors.success;
    case ReturnStatus.rejected:
      return AppColors.error;
    case ReturnStatus.cancelled:
      return AppColors.textSecondary;
  }
}

