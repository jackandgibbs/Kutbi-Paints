// ─── Timeline row ─────────────────────────────────────────────────────────────

class _TimelineStep {
  final String label;
  final DateTime? timestamp;
  final bool isDone;
  final IconData icon;
  final Color? color;

  const _TimelineStep({
    required this.label,
    required this.timestamp,
    required this.isDone,
    required this.icon,
    this.color,
  });
}

class _TimelineRow extends StatelessWidget {
  final _TimelineStep step;
  final bool showLine;

  const _TimelineRow({required this.step, required this.showLine});

  @override
  Widget build(BuildContext context) {
    final activeColor =
        step.color ?? (step.isDone ? AppColors.success : Colors.grey.shade300);

    return Row(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Column(
          children: [
            Container(
              width: 36,
              height: 36,
              decoration: BoxDecoration(
                color: step.isDone
                    ? activeColor.withValues(alpha: 0.12)
                    : Colors.grey.shade100,
                shape: BoxShape.circle,
                border: Border.all(
                  color: step.isDone ? activeColor : Colors.grey.shade300,
                  width: 1.5,
                ),
              ),
              child: Icon(
                step.icon,
                size: 18,
                color: step.isDone ? activeColor : Colors.grey.shade400,
              ),
            ),
            if (showLine)
              Container(
                width: 2,
                height: 40,
                color: step.isDone
                    ? activeColor.withValues(alpha: 0.3)
                    : Colors.grey.shade200,
              ),
          ],
        ),
        const SizedBox(width: 14),
        Expanded(
          child: Padding(
            padding: EdgeInsets.only(bottom: showLine ? 12 : 0, top: 6),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  step.label,
                  style: GoogleFonts.poppins(
                    fontSize: 13,
                    fontWeight:
                        step.isDone ? FontWeight.w600 : FontWeight.w400,
                    color: step.isDone
                        ? AppColors.textPrimary
                        : AppColors.textLight,
                  ),
                ),
                if (step.timestamp != null && step.isDone) ...[
                  const SizedBox(height: 2),
                  Text(
                    DateFormat('dd MMM yyyy, hh:mm a')
                        .format(step.timestamp!),
                    style: GoogleFonts.poppins(
                      fontSize: 11,
                      color: AppColors.textSecondary,
                    ),
                  ),
                ],
              ],
            ),
          ),
        ),
      ],
    );
  }
}

// ─── Cancel button ────────────────────────────────────────────────────────────

class _CancelButton extends ConsumerStatefulWidget {
  final String returnId;
  const _CancelButton({required this.returnId});

  @override
  ConsumerState<_CancelButton> createState() => _CancelButtonState();
}

class _CancelButtonState extends ConsumerState<_CancelButton> {
  bool _loading = false;

  @override
  Widget build(BuildContext context) {
    return SizedBox(
      width: double.infinity,
      child: OutlinedButton(
        onPressed: _loading ? null : _cancel,
        style: OutlinedButton.styleFrom(
          foregroundColor: AppColors.error,
          side: const BorderSide(color: AppColors.error),
          padding: const EdgeInsets.symmetric(vertical: 14),
          shape: RoundedRectangleBorder(
            borderRadius: BorderRadius.circular(14),
          ),
        ),
        child: Text(
          _loading ? 'Cancelling…' : 'Cancel Return Request',
          style: GoogleFonts.poppins(fontWeight: FontWeight.w600),
        ),
      ),
    );
  }

  Future<void> _cancel() async {
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (_) => AlertDialog(
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
        title: Text('Cancel Return',
            style: GoogleFonts.poppins(fontWeight: FontWeight.w700)),
        content: Text('Are you sure you want to cancel this return request?',
            style: GoogleFonts.poppins()),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context, false),
            child: Text('No', style: GoogleFonts.poppins()),
          ),
          ElevatedButton(
            onPressed: () => Navigator.pop(context, true),
            style: ElevatedButton.styleFrom(backgroundColor: AppColors.error),
            child: Text('Yes, Cancel',
                style: GoogleFonts.poppins(color: Colors.white)),
          ),
        ],
      ),
    );

    if (confirmed != true || !mounted) return;

    setState(() => _loading = true);
    try {
      await ref.read(dataServiceProvider).cancelReturnRequest(widget.returnId);
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Return cancelled.', style: GoogleFonts.poppins()),
            backgroundColor: AppColors.success,
          ),
        );
        context.pop();
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Error: $e', style: GoogleFonts.poppins()),
            backgroundColor: AppColors.error,
          ),
        );
      }
    } finally {
      if (mounted) setState(() => _loading = false);
    }
  }
}

// ─── Return Bill Card ─────────────────────────────────────────────────────────

class _ReturnBillCard extends StatefulWidget {
  final ReturnRequestModel returnRequest;
  const _ReturnBillCard({required this.returnRequest});

  @override
  State<_ReturnBillCard> createState() => _ReturnBillCardState();
}

class _ReturnBillCardState extends State<_ReturnBillCard> {
  bool _isLoading = false;

  Future<void> _openBill() async {
    final url = widget.returnRequest.billUrl;
    if (url == null || url.isEmpty) return;

    setState(() => _isLoading = true);
    try {
      final uri = Uri.parse(url);
      final res = await http.get(uri);
      if (res.statusCode == 200) {
        await Printing.layoutPdf(
          onLayout: (_) => res.bodyBytes,
          name: 'Return_Bill_${widget.returnRequest.displayId}.pdf',
        );
        return;
      }
    } catch (_) {
      // Fallback below
    } finally {
      if (mounted) setState(() => _isLoading = false);
    }

    try {
      final uri = Uri.parse(url);
      if (await canLaunchUrl(uri)) {
        await launchUrl(uri, mode: LaunchMode.externalApplication);
      }
    } catch (_) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Could not open bill PDF', style: GoogleFonts.poppins()),
            backgroundColor: AppColors.error,
          ),
        );
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final req = widget.returnRequest;

    return Container(
      width: double.infinity,
      padding: const EdgeInsets.all(16),
      decoration: BoxDecoration(
        color: const Color(0xFF7C3AED).withValues(alpha: 0.05),
        borderRadius: BorderRadius.circular(16),
        border: Border.all(
          color: const Color(0xFF7C3AED).withValues(alpha: 0.3),
        ),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              Container(
                padding: const EdgeInsets.all(8),
                decoration: BoxDecoration(
                  color: const Color(0xFF7C3AED).withValues(alpha: 0.12),
                  borderRadius: BorderRadius.circular(10),
                ),
                child: const Icon(
                  Icons.receipt_long_rounded,
                  color: Color(0xFF7C3AED),
                  size: 24,
                ),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      'Return Bill / Credit Note',
                      style: GoogleFonts.poppins(
                        fontSize: 14,
                        fontWeight: FontWeight.w700,
                        color: const Color(0xFF7C3AED),
                      ),
                    ),
                    Text(
                      req.refundAmount > 0
                          ? 'Approved Refund: ₹${req.refundAmount.toStringAsFixed(0)}'
                          : 'Official Return Invoice Available',
                      style: GoogleFonts.poppins(
                        fontSize: 12,
                        color: AppColors.textSlateLight,
                      ),
                    ),
                  ],
                ),
              ),
            ],
          ),
          const SizedBox(height: 14),
          SizedBox(
            width: double.infinity,
            child: ElevatedButton.icon(
              onPressed: _isLoading ? null : _openBill,
              icon: _isLoading
                  ? const SizedBox(
                      width: 16,
                      height: 16,
                      child: CircularProgressIndicator(
                        strokeWidth: 2,
                        color: Colors.white,
                      ),
                    )
                  : const Icon(Icons.download_rounded, size: 18),
              label: Text(
                _isLoading ? 'Loading Bill…' : 'View / Download Return Bill',
                style: GoogleFonts.poppins(
                  fontWeight: FontWeight.w600,
                  fontSize: 13,
                ),
              ),
              style: ElevatedButton.styleFrom(
                backgroundColor: const Color(0xFF7C3AED),
                foregroundColor: Colors.white,
                padding: const EdgeInsets.symmetric(vertical: 12),
                shape: RoundedRectangleBorder(
                  borderRadius: BorderRadius.circular(10),
                ),
              ),
            ),
          ),
        ],
      ),
    );
  }
}

